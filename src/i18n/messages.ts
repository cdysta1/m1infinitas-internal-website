export function translate(language: Language, message: string, values: MessageValues = {}): string {
  const english = EN_MESSAGES[message];
  const template = language === 'en' && typeof english === 'string' ? english : message;
  return template.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder));
}

export function translateError(language: Language, error: unknown, fallback: string): string {
  const message = error instanceof Error ? error.message : '';
  const lengthError = /^项目介绍不能超过 (\d+) 字$/.exec(message);
  if (lengthError) return translate(language, '项目介绍不能超过 {count} 字', { count: lengthError[1] });
  return translate(language, message || fallback);
}
